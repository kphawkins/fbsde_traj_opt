#include "fbsde_traj_opt/counter_based_normal_sampler.hpp"
#include "fbsde_traj_opt/normal_distribution_concepts.hpp"
#include "fbsde_traj_opt/sde_term_concepts.hpp"
#include "fbsde_traj_opt/utils/result.hpp"

namespace fbsde_traj_opt {

// A fixed-size batch of trajectories sampled from a closed-loop forward SDE.
//
// The batch holds `NumTrajectories` independent rollouts over stages 0..`NumStages`-1: a state at
// every stage, and a control at every stage but the last, since no control is applied once the
// terminal state is reached. Every rollout is generated by drawing x_0 from an initial
// distribution and then repeatedly applying the policy and the forward step
//
//   u_k = pi(k, x_k),
//   x_{k+1} = x_k + f(k, x_k) + B(k, x_k) * u_k + Sigma(k, x_k) * z_k.
//
// Storage layout: states and controls are grouped by stage, one `N x NumTrajectories` matrix per
// stage, rather than by trajectory. Everything this container is asked for afterwards is a
// cross-sectional question -- the state distribution at a stage, its mean, the spread around it --
// and each of those is then a single Eigen reduction over one contiguous matrix.
//
// The whole batch lives inline: `std::array` of fixed-size Eigen matrices, no indirection and no
// allocation anywhere in this class. That makes the object itself large -- `NumStages * N *
// NumTrajectories` scalars -- so a caller sampling a big batch should give it storage of its own
// (`std::make_unique<TrajectoryBatch<...>>(...)`) rather than leaving it on the stack.
//
// `N` is the compile-time state dimension, `M` the compile-time control dimension, and `Scalar`
// defaults to `double`.
template <int N, int M, std::size_t NumTrajectories, std::size_t NumStages, typename Scalar = double>
class TrajectoryBatch {
  static_assert(NumTrajectories >= 1, "A trajectory batch needs at least one trajectory.");
  static_assert(NumStages >= 2, "A trajectory batch needs at least an initial and a terminal stage.");

 public:
  using State = Eigen::Matrix<Scalar, N, 1>;
  using Control = Eigen::Matrix<Scalar, M, 1>;

  // The states, respectively controls, of every trajectory at one stage: one column per
  // trajectory.
  using StateBlock = Eigen::Matrix<Scalar, N, static_cast<int>(NumTrajectories)>;
  using ControlBlock = Eigen::Matrix<Scalar, M, static_cast<int>(NumTrajectories)>;

  // One value per stage, indexed by stage. Returned by ExpectedCostToGo().
  using StageValues = std::array<Scalar, NumStages>;

  static constexpr std::size_t kStateDim = static_cast<std::size_t>(N);
  static constexpr std::size_t kControlDim = static_cast<std::size_t>(M);
  static constexpr std::size_t kNumTrajectories = NumTrajectories;
  static constexpr std::size_t kNumStages = NumStages;

  // The number of stages at which a control is applied: every stage but the terminal one.
  static constexpr std::size_t kNumControlStages = NumStages - 1;

  // Samples a batch of `NumTrajectories` trajectories of `NumStages` stages each.
  //
  // `initial_distribution` supplies the law of x_0, `control_policy` closes the loop at every
  // stage, `forward_model` advances the state, and `seed` fixes the noise. Sampling is performed
  // by the private constructor, so a TrajectoryBatch is filled the moment it exists and is
  // immutable thereafter.
  //
  // Reproducibility: the noise is drawn from a CounterBasedNormalSampler, whose variate at a
  // coordinate depends only on the seed and the coordinate. Two batches sampled with the same
  // seed, `NumTrajectories`, `NumStages`, and `N` therefore see identical noise even if the
  // dynamics, the cost, or the policy differ -- which is what makes two such batches directly
  // comparable, one trajectory against its counterpart.
  //
  // Fails if the initial distribution's covariance cannot be Cholesky-factored, which is the one
  // precondition of NormalDistribution (positive definiteness) that the concept itself cannot
  // check.
  //
  // The returned batch is moved out of the factory once. For a batch large enough for that to
  // matter, the move is still cheap next to the sampling that filled it.
  template <typename StateDriftTermT,
            typename ControlDriftMatTermT,
            typename DiffusionTermT,
            typename ControlPolicyT,
            typename InitialDistributionT>
    requires SdeControlPolicyTerm<ControlPolicyT, State, Control> && NormalDistribution<InitialDistributionT, State>
  static auto Make(
      const ComposedForwardSdeModel<N, M, StateDriftTermT, ControlDriftMatTermT, DiffusionTermT, Scalar>& forward_model,
      const ControlPolicyT& control_policy,
      const InitialDistributionT& initial_distribution,
      std::uint64_t seed) noexcept -> Result<TrajectoryBatch> {
    // Eigen's fixed-size LLT keeps the factorization allocation-free.
    const Eigen::Matrix<Scalar, N, N> covariance = initial_distribution.Covariance();
    const Eigen::LLT<Eigen::Matrix<Scalar, N, N>> covariance_factorization(covariance);
    RESULT_ASSERT(covariance_factorization.info() == Eigen::Success,
                  "TrajectoryBatch::Make: the initial distribution's covariance is not positive definite.");

    return SuccessResult(TrajectoryBatch(forward_model,
                                         control_policy,
                                         State(initial_distribution.Mean()),
                                         Eigen::Matrix<Scalar, N, N>(covariance_factorization.matrixL()),
                                         seed));
  }

  // Returns the states of every trajectory at `stage`, one column per trajectory.
  //
  // Precondition: `stage < kNumStages`.
  [[nodiscard]] auto StatesAtStage(std::size_t stage) const noexcept -> const StateBlock& { return states_[stage]; }

  // Returns the controls applied by every trajectory at `stage`, one column per trajectory.
  //
  // Precondition: `stage < kNumControlStages`; there is no control at the terminal stage.
  [[nodiscard]] auto ControlsAtStage(std::size_t stage) const noexcept -> const ControlBlock& {
    return controls_[stage];
  }

  // Returns the state of `trajectory` at `stage`.
  //
  // Precondition: `trajectory < kNumTrajectories` and `stage < kNumStages`.
  [[nodiscard]] auto StateAt(std::size_t trajectory, std::size_t stage) const noexcept -> State {
    return states_[stage].col(static_cast<Eigen::Index>(trajectory));
  }

  // Returns the control applied by `trajectory` at `stage`.
  //
  // Precondition: `trajectory < kNumTrajectories` and `stage < kNumControlStages`.
  [[nodiscard]] auto ControlAt(std::size_t trajectory, std::size_t stage) const noexcept -> Control {
    return controls_[stage].col(static_cast<Eigen::Index>(trajectory));
  }

  // Returns the sample mean state over all trajectories at `stage` -- the mean trajectory's state
  // at that stage.
  //
  // Precondition: `stage < kNumStages`.
  [[nodiscard]] auto MeanStateAtStage(std::size_t stage) const noexcept -> State {
    return states_[stage].rowwise().mean();
  }

  // Returns the sample mean control over all trajectories at `stage`.
  //
  // Precondition: `stage < kNumControlStages`.
  [[nodiscard]] auto MeanControlAtStage(std::size_t stage) const noexcept -> Control {
    return controls_[stage].rowwise().mean();
  }

  // Returns the seed the batch was sampled with.
  [[nodiscard]] auto seed() const noexcept -> std::uint64_t { return seed_; }

  // Returns the expected cost-to-go at every stage under `cost_model`.
  //
  // The cost-to-go of one trajectory from stage k is the cost it actually accrues from k onwards:
  // the running cost at every stage from k up to but not including the terminal stage, plus the
  // terminal cost,
  //
  //   c_k = sum_{j=k}^{K-1} l(j, x_j, u_j) + phi(x_K),     c_K = phi(x_K).
  //
  // Element k of the returned array is the mean of c_k over the batch, which is the Monte Carlo
  // estimate of the value function evaluated on the batch's own stage-k state distribution. Note
  // what that does and does not mean: it averages over the trajectories that reached stage k
  // along this batch's rollouts, so it is the value of the policy under the sampled state
  // distribution at k, not the value of starting fresh from some other distribution there.
  //
  // Computed by one backward sweep -- each trajectory's c_k is its own c_{k+1} plus one running
  // cost -- so the whole array costs one running-cost evaluation per trajectory per stage rather
  // than the quadratic count a forward re-summation from every stage would need.
  template <typename RunningCostTermT, typename TerminalCostTermT>
  [[nodiscard]] auto ExpectedCostToGo(
      const ComposedCostSdeModel<N, M, RunningCostTermT, TerminalCostTermT, Scalar>& cost_model) const noexcept
      -> StageValues {
    // The cost-to-go of each trajectory from the stage currently being visited, carried backwards.
    Eigen::Matrix<Scalar, static_cast<int>(NumTrajectories), 1> cost_to_go;
    for (std::size_t trajectory = 0; trajectory < NumTrajectories; ++trajectory) {
      cost_to_go[static_cast<Eigen::Index>(trajectory)] =
          cost_model.terminal_cost()(StateAt(trajectory, NumStages - 1));
    }

    StageValues expected_cost_to_go{};
    expected_cost_to_go[NumStages - 1] = cost_to_go.mean();

    for (std::size_t stage = kNumControlStages; stage-- > 0;) {
      for (std::size_t trajectory = 0; trajectory < NumTrajectories; ++trajectory) {
        cost_to_go[static_cast<Eigen::Index>(trajectory)] +=
            cost_model.running_cost()(stage, StateAt(trajectory, stage), ControlAt(trajectory, stage));
      }
      expected_cost_to_go[stage] = cost_to_go.mean();
    }

    return expected_cost_to_go;
  }

 private:
  // Samples the whole batch. Private because a TrajectoryBatch has no meaningful empty state:
  // Make() is the only way to obtain one, and by the time it returns, every trajectory is filled.
  //
  // `initial_mean` and `initial_covariance_factor` are the mean and lower Cholesky factor of the
  // initial distribution; Make() computes the factor so that a failed factorization is reported
  // as an error rather than discovered here, where there is no way to report it.
  template <typename ForwardModelT, typename ControlPolicyT>
  TrajectoryBatch(const ForwardModelT& forward_model,
                  const ControlPolicyT& control_policy,
                  const State& initial_mean,
                  const Eigen::Matrix<Scalar, N, N>& initial_covariance_factor,
                  std::uint64_t seed) noexcept
      : seed_(seed) {
    const CounterBasedNormalSampler sampler(seed);

    // The sampler's stage coordinate indexes the state a draw produces, not the transition it
    // drives: coordinate 0 produces x_0 from the initial distribution, and coordinate k+1
    // produces x_{k+1} from the k -> k+1 transition. Each stage's noise is thus used exactly
    // once, and the initial draw needs no coordinate axis of its own.
    State noise = State::Zero();
    for (std::size_t trajectory = 0; trajectory < NumTrajectories; ++trajectory) {
      sampler.FillNoise(trajectory, 0, noise);
      states_[0].col(static_cast<Eigen::Index>(trajectory)) = initial_mean + (initial_covariance_factor * noise);
    }

    for (std::size_t stage = 0; stage < kNumControlStages; ++stage) {
      for (std::size_t trajectory = 0; trajectory < NumTrajectories; ++trajectory) {
        const auto column = static_cast<Eigen::Index>(trajectory);
        const State state = states_[stage].col(column);

        const Control control = control_policy(stage, state);
        controls_[stage].col(column) = control;

        sampler.FillNoise(trajectory, stage + 1, noise);
        states_[stage + 1].col(column) = forward_model(stage, state, control, noise);
      }
    }
  }

  std::array<StateBlock, NumStages> states_;
  std::array<ControlBlock, kNumControlStages> controls_;
  std::uint64_t seed_;
};

}  // namespace fbsde_traj_opt

#endif  // FBSDE_TRAJ_OPT_TRAJECTORY_BATCH_HPP_
